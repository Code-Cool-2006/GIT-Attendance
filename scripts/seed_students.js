const lines = rawData.trim().split('\n');
const csvLines = ['Roll Number, Name, Email, Phone, Department, Semester'];
const dbRows = [];

lines.forEach(line => {
  const parts = line.split('\t');
  if (parts.length >= 2) {
    const roll = parts[0].trim();
    const name = parts[1].trim();
    const email = `${roll.toLowerCase()}@git.edu`;
    csvLines.push(`${roll}, ${name}, ${email}, , CSE, 4`);
    dbRows.push({ roll, name, email });
  }
});

fs.writeFileSync('./students_list.csv', csvLines.join('\n'));
console.log(`Generated students_list.csv with ${dbRows.length} students!`);

async function seedDatabase() {
  const dbUrl = process.env.DATABASE_URL;
  if (!dbUrl) {
    console.log('No DATABASE_URL found in .env, skipping DB seed.');
    return;
  }
  const sql = neon(dbUrl);
  let count = 0;
  for (const s of dbRows) {
    try {
      await sql`
        INSERT INTO students (id, roll_number, name, email, department, semester)
        VALUES (gen_random_uuid(), ${s.roll}, ${s.name}, ${s.email}, 'CSE', 4)
        ON CONFLICT (roll_number) DO NOTHING;
      `;
      count++;
    } catch (e) {
      console.error(`Failed to insert ${s.roll}:`, e.message);
    }
  }
  console.log(`Successfully seeded ${count} students into Neon database!`);
}

seedDatabase();
